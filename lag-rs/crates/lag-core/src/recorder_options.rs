//! Mirrors Services/RecorderOptions.cs: the complete immutable-at-start recording snapshot.

#[derive(Debug, Clone, PartialEq)]
pub struct AppAudioCapture {
    pub exe_name: String,
    pub volume: f32,
}

#[derive(Debug, Clone, PartialEq)]
pub struct RecorderOptions {
    pub buffer_seconds: i32,
    pub frame_rate: i32,
    pub width: u32,
    pub height: u32,
    pub output_width: u32,
    pub output_height: u32,
    pub video_bitrate_kbps: i32,
    pub adapter_index: i32,
    pub preferred_encoder: Option<String>,
    pub monitor_id: Option<String>,
    pub library_path: Option<String>,
    pub file_format: String,
    pub microphone_id: Option<String>,
    pub mic_volume: f32,
    pub mic_force_mono: bool,
    pub input_gate_auto: bool,
    pub input_gate_threshold: f32,
    pub noise_suppression: bool,
    pub mic_start_muted: bool,
    pub audio_capture_mode: String,
    pub audio_mode_by_target: bool,
    pub system_audio_device_id: Option<String>,
    pub audio_apps: Vec<AppAudioCapture>,
    pub separate_audio_tracks: bool,
    /// Rust-only: true = record the desktop while the game is out of focus (settings `GameFocusMode` = "desktop").
    pub record_desktop_when_unfocused: bool,
    pub system_audio_enabled: bool,
    pub system_audio_volume: i32,
    pub game_audio_enabled: bool,
    pub game_audio_volume: i32,
    pub webcam_overlay: bool,
    pub webcam_device_id: Option<String>,
    pub webcam_x: f64,
    pub webcam_y: f64,
    pub webcam_scale: f64,
    /// (width, height, fps) requested from the camera; zeros = Auto.
    pub webcam_format: (u32, u32, u32),
    pub keys_overlay: bool,
    pub keys_x: f64,
    pub keys_y: f64,
    pub keys_scale: f64,
    pub stats_overlay: bool,
    pub stats_x: f64,
    pub stats_y: f64,
    pub stats_scale: f64,
    pub stats_detail: i32,
}

impl Default for RecorderOptions {
    fn default() -> Self {
        Self {
            buffer_seconds: 60,
            frame_rate: 30,
            width: Default::default(),
            height: Default::default(),
            output_width: Default::default(),
            output_height: Default::default(),
            video_bitrate_kbps: 20000,
            adapter_index: Default::default(),
            preferred_encoder: Default::default(),
            monitor_id: Default::default(),
            library_path: Default::default(),
            file_format: "mp4".into(),
            microphone_id: Default::default(),
            mic_volume: 1.0,
            mic_force_mono: Default::default(),
            input_gate_auto: true,
            input_gate_threshold: 0.08,
            noise_suppression: Default::default(),
            mic_start_muted: Default::default(),
            audio_capture_mode: "all".into(),
            audio_mode_by_target: Default::default(),
            system_audio_device_id: Default::default(),
            audio_apps: Vec::new(),
            separate_audio_tracks: Default::default(),
            record_desktop_when_unfocused: false,
            system_audio_enabled: true,
            system_audio_volume: 100,
            game_audio_enabled: true,
            game_audio_volume: 100,
            webcam_overlay: Default::default(),
            webcam_device_id: Default::default(),
            webcam_x: 0.97,
            webcam_y: 0.95,
            webcam_scale: 0.24,
            webcam_format: (0, 0, 0),
            keys_overlay: Default::default(),
            keys_x: 0.03,
            keys_y: 0.95,
            keys_scale: 0.20,
            stats_overlay: Default::default(),
            stats_x: 0.5,
            stats_y: 0.02,
            stats_scale: 0.045,
            stats_detail: 1,
        }
    }
}
