//! Mirrors Services/ClipMetadata.cs: hidden MD5-keyed sidecars and legacy migration.

use serde::{Deserialize, Serialize};
use std::{
    io,
    path::{Path, PathBuf},
};

#[derive(Debug, Default, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default, rename_all = "PascalCase")]
pub struct ClipMetadata {
    pub game: Option<String>,
    pub exe: Option<String>,
    pub favorite: bool,
    pub edited: bool,
    pub duration_seconds: Option<f64>,
    /// The clip's cloud id (lag_cloud::ClipId, docs/spec/cloud.md §3): set the first time the clip meets the
    /// cloud, the same on every PC. Omitted while unset, so the C# build's files stay byte-identical.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub cloud_id: Option<String>,
}

impl ClipMetadata {
    pub fn from_json(text: &str) -> serde_json::Result<Self> {
        serde_json::from_str(text.trim_start_matches('\u{feff}'))
    }

    pub fn to_json(&self) -> serde_json::Result<String> {
        crate::netjson::to_string(self)
    }
}

/// MD5 of UTF-8 `clipPath.ToLowerInvariant()`, uppercase hex; no path normalization.
pub fn path_hash(clip_path: &str) -> String {
    // .NET invariant casing is scalar/simple casing (not Unicode full case folding).
    // In particular U+0130 is unchanged, unlike Rust's expanding lowercase mapping.
    let lower: String =
        clip_path.chars().map(|c| if c == '\u{130}' { c } else { c.to_lowercase().next().unwrap_or(c) }).collect();
    format!("{:X}", md5::compute(lower.as_bytes()))
}

pub fn default_directory() -> Option<PathBuf> {
    crate::hardware::local_appdata().map(|p| p.join("Lag/metadata"))
}

#[derive(Debug, Clone)]
pub struct ClipMetadataStore {
    directory: PathBuf,
}

impl ClipMetadataStore {
    pub fn new(directory: impl Into<PathBuf>) -> Self {
        Self { directory: directory.into() }
    }
    pub fn for_user() -> Option<Self> {
        default_directory().map(Self::new)
    }
    pub fn cache_path(&self, clip_path: &str) -> PathBuf {
        self.directory.join(format!("{}.json", path_hash(clip_path)))
    }
    pub fn legacy_path(clip_path: &str) -> PathBuf {
        PathBuf::from(format!("{clip_path}.json"))
    }

    /// Best effort, like C#: a corrupt cache does not fall through to the legacy sidecar.
    pub fn read(&self, clip_path: &str) -> Option<ClipMetadata> {
        let cache = self.cache_path(clip_path);
        let legacy = Self::legacy_path(clip_path);
        let cached = cache.exists();
        let path = if cached { &cache } else { &legacy };
        let text = std::fs::read_to_string(path).ok()?;
        let meta: Option<ClipMetadata> = serde_json::from_str(text.trim_start_matches('\u{feff}')).ok()?;
        if !cached {
            if let Some(ref meta) = meta {
                self.write(clip_path, meta);
            }
        }
        meta
    }

    /// Reports errors for callers that need them; `write` provides the C# best-effort API.
    pub fn try_write(&self, clip_path: &str, meta: &ClipMetadata) -> io::Result<()> {
        std::fs::create_dir_all(&self.directory)?;
        let json = meta.to_json().map_err(io::Error::other)?;
        std::fs::write(self.cache_path(clip_path), json)?;
        let _ = std::fs::remove_file(Self::legacy_path(clip_path));
        Ok(())
    }
    pub fn write(&self, clip_path: &str, meta: &ClipMetadata) {
        if let Err(e) = self.try_write(clip_path, meta) {
            log::debug!("[ClipMeta] write failed: {e}");
        }
    }
    pub fn update(&self, clip_path: &str, mutate: impl FnOnce(&mut ClipMetadata)) {
        let mut meta = self.read(clip_path).unwrap_or_default();
        mutate(&mut meta);
        self.write(clip_path, &meta);
    }
    pub fn set_duration(&self, clip_path: &str, seconds: f64) {
        self.update(clip_path, |m| m.duration_seconds = Some(seconds));
    }
    pub fn set_favorite(&self, clip_path: &str, favorite: bool) {
        self.update(clip_path, |m| m.favorite = favorite);
    }
    pub fn set_cloud_id(&self, clip_path: &str, id: &str) {
        self.update(clip_path, |m| m.cloud_id = Some(id.to_owned()));
    }
    pub fn set_edited(&self, clip_path: &str, edited: bool) {
        self.update(clip_path, |m| m.edited = edited);
    }
    pub fn delete(&self, clip_path: &str) {
        let _ = std::fs::remove_file(self.cache_path(clip_path));
        let _ = std::fs::remove_file(Self::legacy_path(clip_path));
    }
    pub fn directory(&self) -> &Path {
        &self.directory
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn schema_and_hash() {
        // Independently generated by .NET 8 MD5.HashData(UTF8(path.ToLowerInvariant())).
        assert_eq!(path_hash(r"C:\Clips\Replay.mp4"), "E70506024595A2FBC13F5ECC2858A8C3");
        assert_eq!(ClipMetadata::default().to_json().unwrap(), "{\r\n  \"Game\": null,\r\n  \"Exe\": null,\r\n  \"Favorite\": false,\r\n  \"Edited\": false,\r\n  \"DurationSeconds\": null\r\n}");
        assert_eq!(path_hash(r"C:\Clips\Replay.mp4"), path_hash(r"c:\clips\replay.mp4"));
        assert_ne!(path_hash(r"C:\Clips\Replay.mp4"), path_hash("C:/Clips/Replay.mp4"));
    }
    #[test]
    fn real_clip_path_matches_an_existing_sidecar_filename() {
        let Some(dir) = default_directory() else {
            return;
        };
        if !dir.exists() {
            return;
        }
        let Some(settings) =
            crate::settings::default_path().and_then(|p| crate::settings::SettingsData::load(&p).ok().flatten())
        else {
            eprintln!("Real settings unavailable; cannot locate known clip paths");
            return;
        };
        let Some(library) = settings.library_path.filter(|s| !s.is_empty()) else {
            return;
        };
        let entries = std::fs::read_dir(&dir).unwrap();
        let names: std::collections::HashSet<_> = entries.map(|e| e.unwrap().file_name()).collect();
        if names.is_empty() {
            return;
        }
        let store = ClipMetadataStore::new(dir);
        let mut clips = 0;
        for entry in std::fs::read_dir(library).unwrap() {
            let path = entry.unwrap().path();
            if path.extension().is_some_and(|e| {
                matches!(
                    e.to_string_lossy().to_lowercase().as_str(),
                    "mp4" | "mkv" | "mov" | "avi" | "gif" | "png" | "jpg"
                )
            }) {
                clips += 1;
                let cache = store.cache_path(&path.to_string_lossy());
                if names.contains(cache.file_name().unwrap()) {
                    return;
                }
            }
        }
        if clips > 0 {
            panic!("No real clip path hashes to an existing metadata filename");
        }
    }
    #[test]
    fn every_real_sidecar_round_trips() {
        let Some(dir) = default_directory() else {
            return;
        };
        if !dir.exists() {
            eprintln!("No {dir:?}; skipping real sidecars");
            return;
        }
        // Sidecars written by older C# builds lack keys added later (e.g. DurationSeconds). The current C#
        // would re-write those with every key present, exactly like Rust does, so: files that already have
        // every key must round-trip byte-for-byte; older files must keep every value and only GAIN keys.
        let (mut exact, mut older) = (0, 0);
        for entry in std::fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            if path.extension().is_some_and(|x| x == "json") {
                let original = std::fs::read_to_string(&path).unwrap();
                let parsed = ClipMetadata::from_json(&original).unwrap();
                let written = parsed.to_json().unwrap();
                let orig_v: serde_json::Value = serde_json::from_str(&original).unwrap();
                let new_v: serde_json::Value = serde_json::from_str(&written).unwrap();
                let (o, n) = (orig_v.as_object().unwrap(), new_v.as_object().unwrap());
                if o.len() == n.len() {
                    assert_eq!(written, original, "{path:?}");
                    exact += 1;
                } else {
                    for (k, v) in o {
                        assert_eq!(n.get(k), Some(v), "{path:?}: value of {k} changed");
                    }
                    assert_eq!(ClipMetadata::from_json(&written).unwrap(), parsed, "{path:?}");
                    older += 1;
                }
            }
        }
        eprintln!("real sidecars: {exact} byte-identical, {older} older-format (only gained new keys)");
    }
    #[test]
    fn legacy_migration_and_delete() {
        let dir = crate::test_directory("metadata");
        let store = ClipMetadataStore::new(dir.join("cache"));
        let clip = dir.join("clip.mp4").to_string_lossy().into_owned();
        std::fs::write(ClipMetadataStore::legacy_path(&clip), "{\"Favorite\":true}").unwrap();
        assert!(store.read(&clip).unwrap().favorite);
        assert!(!ClipMetadataStore::legacy_path(&clip).exists());
        assert!(store.cache_path(&clip).exists());
        store.set_duration(&clip, 42.5);
        store.set_edited(&clip, true);
        assert_eq!(store.read(&clip).unwrap().duration_seconds, Some(42.5));
        std::fs::write(store.cache_path(&clip), "broken").unwrap();
        std::fs::write(ClipMetadataStore::legacy_path(&clip), "{}").unwrap();
        assert!(store.read(&clip).is_none());
        store.delete(&clip);
        assert!(!store.cache_path(&clip).exists());
        std::fs::remove_dir_all(dir).unwrap();
    }
}

/// One stable name per game for grouping/filters. Games without a known exe fall back to their WINDOW TITLE,
/// which some games change constantly: Minecraft Java shows "Minecraft* 1.20.1 - Singleplayer",
/// "Minecraft 1.20.1 - Multiplayer (3rd-party Server)", etc. -> one "Minecraft" group (owner, 2026-11-16).
/// Also drops the "unsaved changes" asterisk some titles carry.
pub fn normalize_game_name(name: &str) -> String {
    let trimmed = name.trim().trim_end_matches('*').trim();
    if trimmed.len() >= 9 && trimmed[..9].eq_ignore_ascii_case("minecraft") {
        return "Minecraft".into();
    }
    trimmed.to_string()
}

#[cfg(test)]
mod normalize_tests {
    use super::normalize_game_name as n;
    #[test]
    fn minecraft_titles_group_and_others_stay() {
        assert_eq!(n("Minecraft* 1.20.1"), "Minecraft");
        assert_eq!(n("Minecraft* 1.20.1 - Singleplayer"), "Minecraft");
        assert_eq!(n("Minecraft 1.21 - Multiplayer (3rd-party Server)"), "Minecraft");
        assert_eq!(n("minecraft"), "Minecraft");
        assert_eq!(n("Counter-Strike 2"), "Counter-Strike 2");
        assert_eq!(n("Dying Light: The Beast"), "Dying Light: The Beast");
        assert_eq!(n("  Grand Theft Auto V "), "Grand Theft Auto V");
    }
}
